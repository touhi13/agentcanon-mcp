import path from 'path';
import { MasterConfig, Rule } from '../domain/schema.js';

export interface GeneratedProjection {
  filePath: string;
  content: string;
}

export interface AgentAdapter {
  id: string;
  name: string;
  generate(config: MasterConfig, projectRoot: string): GeneratedProjection[];
}

export function sortRulesDeterministically(rules: Rule[]): Rule[] {
  return [...rules].sort((a, b) => {
    if (a.priority !== b.priority) {
      return b.priority - a.priority; // Higher priority first
    }
    return a.id.localeCompare(b.id);
  });
}

export function assertSafeRelativePath(projectRoot: string, targetPath: string): string {
  const resolved = path.resolve(projectRoot, targetPath);
  const normalizedRoot = path.resolve(projectRoot);
  if (!resolved.startsWith(normalizedRoot)) {
    throw new Error(`Security Violation: Path traversal detected -> ${targetPath}`);
  }
  return resolved;
}

export const codexAdapter: AgentAdapter = {
  id: 'codex',
  name: 'OpenAI Codex (AGENTS.md)',
  generate(config, projectRoot) {
    const activeRules = sortRulesDeterministically(
      config.rules.filter(r => r.enabled && r.targets.includes('codex'))
    );
    if (activeRules.length === 0) return [];

    const byDir = new Map<string, Rule[]>();
    for (const rule of activeRules) {
      const dir = rule.scope.directory?.trim().replace(/^[/\\]+|[/\\]+$/g, '') || '';
      const list = byDir.get(dir) ?? [];
      list.push(rule);
      byDir.set(dir, list);
    }

    const outputs: GeneratedProjection[] = [];
    for (const [dir, rules] of [...byDir.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
      const targetPath = dir ? path.join(dir, 'AGENTS.md') : 'AGENTS.md';
      const safePath = assertSafeRelativePath(projectRoot, targetPath);

      const sections = rules.map(r => {
        const scopeNote = r.scope.include.length > 0 && !(r.scope.include.length === 1 && r.scope.include[0] === '**/*')
          ? `\n> **Applies to:** \`${r.scope.include.join('\`, \`')}\``
          : '';
        const excludeNote = r.scope.exclude.length > 0
          ? `\n> **Excludes:** \`${r.scope.exclude.join('\`, \`')}\``
          : '';

        return [
          `## ${r.title} (\`${r.id}\`)`,
          `**Category:** \`${r.category}\` | **Severity:** \`${r.severity.toUpperCase()}\` | **Priority:** ${r.priority}${scopeNote}${excludeNote}`,
          '',
          r.content.trim(),
        ].join('\n');
      });

      const content = [
        `# Codex Instructions for ${config.projectName}`,
        `> Generated by AgentCanon MCP. DO NOT EDIT DIRECTLY.`,
        '',
        sections.join('\n\n---\n\n'),
        ''
      ].join('\n');

      outputs.push({ filePath: safePath, content });
    }
    return outputs;
  }
};

export const cursorAdapter: AgentAdapter = {
  id: 'cursor',
  name: 'Cursor (.mdc rules)',
  generate(config, projectRoot) {
    const activeRules = sortRulesDeterministically(
      config.rules.filter(r => r.enabled && r.targets.includes('cursor'))
    );
    return activeRules.map(r => {
      const targetPath = path.join('.cursor', 'rules', `${r.id}.mdc`);
      const safePath = assertSafeRelativePath(projectRoot, targetPath);
      const globs = r.scope.include.join(', ');
      const content = [
        '---',
        `description: ${r.title}`,
        `globs: ${globs}`,
        `alwaysApply: false`,
        '---',
        '',
        `# ${r.title}`,
        '',
        r.content.trim(),
        ''
      ].join('\n');
      return { filePath: safePath, content };
    });
  }
};

export const claudeAdapter: AgentAdapter = {
  id: 'claude',
  name: 'Claude Code (CLAUDE.md)',
  generate(config, projectRoot) {
    const activeRules = sortRulesDeterministically(
      config.rules.filter(r => r.enabled && r.targets.includes('claude'))
    );
    if (activeRules.length === 0) return [];

    const sections = activeRules.map(r => `### ${r.title}\n${r.content.trim()}`);
    const content = [
      `# CLAUDE.md - ${config.projectName}`,
      `> Managed by AgentCanon MCP`,
      '',
      sections.join('\n\n'),
      ''
    ].join('\n');

    return [{ filePath: assertSafeRelativePath(projectRoot, 'CLAUDE.md'), content }];
  }
};

